-- Tabela de usuários da plataforma
CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(100) UNIQUE NOT NULL,
  senha VARCHAR(255) NOT NULL,
  criado_em TIMESTAMP DEFAULT NOW()
);

-- Tabela de empresas/unidades consumidoras
CREATE TABLE IF NOT EXISTS empresas (
  id_empresa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  razao_social VARCHAR(150) NOT NULL,
  cnpj VARCHAR(18),
  cidade VARCHAR(80),
  estado VARCHAR(2),
  criado_em TIMESTAMP DEFAULT NOW()
);

-- Tabela de faturas/análises cadastradas
CREATE TABLE IF NOT EXISTS faturas (
  id_fatura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empresa BIGINT REFERENCES empresas(id_empresa) ON DELETE SET NULL,
  empresa_nome VARCHAR(150),
  consumo_kwh NUMERIC NOT NULL,
  valor_fatura NUMERIC NOT NULL,
  demanda_contratada NUMERIC NOT NULL,
  demanda_medida NUMERIC NOT NULL,
  multa_reativo BOOLEAN DEFAULT FALSE,
  criado_em TIMESTAMP DEFAULT NOW()
);

-- Tabela de diagnósticos vinculados às faturas
CREATE TABLE IF NOT EXISTS diagnosticos (
  id_diagnostico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_fatura BIGINT REFERENCES faturas(id_fatura) ON DELETE CASCADE,
  economia_estimada NUMERIC,
  viavel_solar BOOLEAN DEFAULT FALSE,
  viavel_acl BOOLEAN DEFAULT FALSE,
  viavel_bess BOOLEAN DEFAULT FALSE,
  criado_em TIMESTAMP DEFAULT NOW()
);

